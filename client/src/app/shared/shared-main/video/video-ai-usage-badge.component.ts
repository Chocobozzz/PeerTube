import { booleanAttribute, ChangeDetectionStrategy, Component, computed, input } from '@angular/core'
import { NgbTooltipModule } from '@ng-bootstrap/ng-bootstrap'
import { VideoAIUsage } from '@peertube/peertube-models'
import { Video } from './video.model'

@Component({
  selector: 'my-video-ai-usage-badge',
  changeDetection: ChangeDetectionStrategy.Eager,
  imports: [ NgbTooltipModule ],
  template: `
    @if (badge(); as badge) {
      <span class="pt-badge" [class]="badge.class" [ngbTooltip]="badge.tooltip" tabindex="0" [attr.aria-label]="badge.tooltip">
        {{ badge.label }}
      </span>
    }
  `
})
export class VideoAIUsageBadgeComponent {
  readonly video = input.required<Pick<Video, 'aiUsage'>>()

  // Compact badges are displayed in video miniatures, so only display them if AI has been used
  readonly compact = input(false, { transform: booleanAttribute })

  readonly badge = computed(() => {
    const aiUsage = this.video().aiUsage
    const compact = this.compact()

    switch (aiUsage?.id) {
      case VideoAIUsage.AI_GENERATED:
        return {
          class: 'badge-purple',
          label: compact ? $localize`AI` : aiUsage.label,
          tooltip: $localize`The creator declared that the whole video, or most of it, has been generated by AI`
        }

      case VideoAIUsage.CONTAINS_AI:
        return {
          class: 'badge-purple',
          label: compact ? $localize`Partly AI` : aiUsage.label,
          tooltip: $localize`The creator declared that some parts of the video have been generated by AI`
        }

      case VideoAIUsage.NO_AI:
        if (compact) return undefined

        return {
          class: 'badge-green',
          label: aiUsage.label,
          tooltip: $localize`The creator declared that nothing seen or heard in the video has been generated by AI`
        }

      default:
        return undefined
    }
  })
}
