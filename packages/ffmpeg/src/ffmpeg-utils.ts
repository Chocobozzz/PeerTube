// Demuxers of the video and audio formats PeerTube accepts
// None of them opens the URLs or files a file may reference
const MEDIA_INPUT_FORMATS = [
  'mov', // mov,mp4,m4a,3gp,3g2,mj2
  'matroska', // matroska,webm
  'ogg',
  'asf',
  'avi',
  'flv',
  'nut',
  'mxf',
  'mpegts',
  'mpeg',
  'mpegvideo',
  'm4v',
  'h264',
  'hevc',
  'mp3',
  'wav',
  'flac',
  'aac',
  'ac3',
  'eac3'
]

// Images PeerTube gives to FFmpeg (watermark, audio cover, animated avatar...)
const IMAGE_INPUT_FORMATS = [
  'image2',
  'png_pipe',
  'jpeg_pipe',
  'webp_pipe',
  'gif',
  'gif_pipe',
  'apng',
  'bmp_pipe'
]

const INPUT_FORMAT_WHITELIST = [ ...MEDIA_INPUT_FORMATS, ...IMAGE_INPUT_FORMATS ].join(',')

// Some demuxers (dash, hls, concat, sdp...) detect the format from the content, whatever the file extension,
// and then open the URLs or the files the input references:
//  * A remote input (pre-signed URL...) could make FFmpeg open any HTTP, TCP or UDP URL (SSRF)
//  * A local input (user upload, import...) could make FFmpeg read another file of the server
// Other protocols (rtmp:// of lives...) are generated by PeerTube and are not restricted
export function buildInputFormatWhitelistOptions (input: unknown, options: { disableFormatWhitelist?: boolean } = {}): string[] {
  if (options.disableFormatWhitelist === true) return []
  if (typeof input !== 'string') return []

  if (/^https?:\/\//i.test(input) || isLocalFileInput(input)) {
    return [ '-format_whitelist', INPUT_FORMAT_WHITELIST ]
  }

  return []
}

function isLocalFileInput (input: string) {
  if (/^file:/i.test(input)) return true
  // Windows drive letter
  if (/^[a-z]:[\\/]/i.test(input)) return true

  // No protocol
  return !/^[a-z][a-z0-9+.-]*:/i.test(input)
}
