/* oxlint-disable @typescript-eslint/no-unused-expressions,@typescript-eslint/require-await */

import { UserNotificationType } from '@peertube/peertube-models'
import {
  cleanupTests,
  createSingleServer,
  PeerTubeServer,
  PluginsCommand,
  setAccessTokensToServers,
  setDefaultVideoChannel,
  waitJobs
} from '@peertube/peertube-server-commands'
import { checkAutoCaption, checkLanguage, checkNoCaption, uploadForTranscription } from '@tests/shared/transcription.js'
import { expect } from 'chai'

describe('Test plugin transcription', function () {
  let server: PeerTubeServer

  before(async function () {
    this.timeout(60000)

    server = await createSingleServer(1)

    await setAccessTokensToServers([ server ])
    await setDefaultVideoChannel([ server ])

    await server.config.enableTranscription()

    await server.plugins.install({ path: PluginsCommand.getPluginTestPath('-transcription') })
  })

  it('Should generate subtitles with the transcriber provided by a plugin', async function () {
    this.timeout(60000)

    const uuid = await uploadForTranscription(server)
    await waitJobs([ server ])

    await server.servers.waitUntilLog(
      `Generate subtitles of ${uuid} \\(channel root_channel, account root\\) with the test plugin transcriber`
    )
    await checkAutoCaption({ servers: [ server ], uuid, captionContains: /Generated by the test plugin transcriber/ })
  })

  it('Should not have installed the builtin transcriber', async function () {
    const logs = await server.servers.getLogContent()

    expect(logs.toString()).to.not.contain('Installing transcriber')
  })

  it('Should not create a caption nor notify if the transcription is empty', async function () {
    this.timeout(60000)

    const uuid = await uploadForTranscription(server, { name: 'empty' })
    await waitJobs([ server ])

    await server.servers.waitUntilLog(`Do not create caption for video ${uuid}: the transcription is empty`)
    await checkNoCaption([ server ], uuid)
    await checkLanguage([ server ], uuid, null)

    const { data } = await server.notifications.list({ start: 0, count: 100 })
    const transcriptionNotifications = data.filter(n => n.type === UserNotificationType.MY_VIDEO_TRANSCRIPTION_GENERATED)

    expect(transcriptionNotifications).to.have.lengthOf(1)
    expect(transcriptionNotifications[0].videoCaption.video.uuid).to.not.equal(uuid)
  })

  it('Should fail if the plugin transcriber returns an unsupported language', async function () {
    this.timeout(60000)

    // Don't wait jobs: the failed transcription job is retried after a long delay
    const uuid = await uploadForTranscription(server, { name: 'invalid language' })

    await server.servers.waitUntilLog('returned an invalid subtitles language', 1, false)
    await checkNoCaption([ server ], uuid)
  })

  it('Should fallback to the builtin transcriber if the plugin transcriber does not generate subtitles', async function () {
    this.timeout(240000)

    const uuid = await uploadForTranscription(server, { name: 'fallback' })
    await waitJobs([ server ])

    await server.servers.waitUntilLog('did not transcribe ' + uuid + ', fallback to the next transcriber')
    await checkAutoCaption({ servers: [ server ], uuid })
  })

  after(async function () {
    await cleanupTests([ server ])
  })
})
